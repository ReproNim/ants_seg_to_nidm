class SubjectLookupError(LookupError):
    """The requested subject cannot be identified in the input NIDM."""


def url_validator(url):
    '''
    Tests whether url is a valide url
    :param url: url to test
    :return: True for valid url else False
    '''
    try:
        result = urlparse(url)
        return all([result.scheme, result.netloc, result.path])

    except:
        return False

def normalise_subject_id(value):
    """Canonical form of a subject id for matching.

    Drops a leading BIDS "sub-" and leading zeros, and compares the lexical
    form only: PyNIDM 4.x writes src_subject_id as "..."^^xsd:string and
    PyNIDM 5 as a plain literal, and rdflib treats the two as different terms.
    """
    text = str(value)
    if text.startswith("sub-"):
        text = text[len("sub-"):]
    stripped = text.lstrip("0")
    # an id of only zeros keeps one, so "0" and "00" stay comparable
    return stripped if stripped or not text else "0"


# ndar:src_subject_id as PyNIDM writes it, and under the http:// form of the
# same NDAR IRI, which other NIDM producers use.
SUBJECT_ID_PREDICATES = (
    URIRef(NIDM_SUBJECTID_URI),
    URIRef(NIDM_SUBJECTID_URI.replace("https://", "http://", 1)),
)


# The anatomical MRI acquisitions a subject node owns: AcquisitionObjects
# generated by an activity associated with that node.
_ANATOMICAL_ACQUISITION_QUERY = prepareQuery(
    """
    PREFIX prov: <http://www.w3.org/ns/prov#>
    PREFIX nidm: <http://purl.org/nidash/nidm#>
    PREFIX nfo:  <http://www.semanticdesktop.org/ontologies/2007/03/22/nfo#>
    SELECT DISTINCT ?acqObj ?filename
    WHERE {
        ?acqObj a nidm:AcquisitionObject ;
                prov:wasGeneratedBy/prov:qualifiedAssociation/prov:agent ?subject ;
                nidm:hadAcquisitionModality nidm:MagneticResonanceImaging ;
                nidm:hadImageUsageType nidm:Anatomical .
        OPTIONAL { ?acqObj nfo:filename ?filename }
    }
    """
)


def _anatomical_acquisitions(graph, subject):
    """Rows (.acqObj, .filename) of the anatomical MRI acquisitions subject owns."""
    return list(graph.query(_ANATOMICAL_ACQUISITION_QUERY, initBindings={"subject": subject}))


def _owns_anatomical_acquisition(graph, subject):
    return bool(_anatomical_acquisitions(graph, subject))


def find_subject(graph, subject_id, forceagent=False, created_agents=()):
    """Return the node in graph that subject_id names: the subject the stats
    belong to. This is the lookup add_seg_data makes; it is public so that a
    caller (a BIDS app) can run the same rule on the input NIDM before
    computing anything. It never changes graph.

    A subject is any node carrying ndar:src_subject_id under the https:// or
    the http:// NDAR IRI, whatever its rdf:type, so a participant typed only
    nidm:Subject, or not typed, is never mistaken for an input without
    subjects. Ids are compared after normalise_subject_id() on both sides. A
    node with several ids counts once.

    - One match: returned.
    - Several matches that all store the same id, character for character
      (some inputs hold two person nodes for one participant, one owning the
      MRI acquisitions and one only an assessment): the one match that owns an
      anatomical MRI acquisition is returned; if none or more than one does,
      SubjectLookupError naming the owners.
    - Several matches whose stored ids differ (they match only after
      normalisation, as "sub-01" and "001" do, and may be different
      participants): SubjectLookupError.
    - No match while graph has subjects: SubjectLookupError whatever
      forceagent says, since attaching the stats to a new agent would detach
      them from that subject's other data.
    - No subjects at all: None with forceagent (the caller creates an agent
      with the id), SubjectLookupError without it.

    These are the rules of segstats_jsonld's find_subject, so both converters
    find the same subject.

    :param created_agents: agents the caller created earlier in the same run;
        they are found when they match, and do not count as input subjects
    :raises SubjectLookupError: when the subject cannot be identified
    """
    stored = [
        (agent, str(sid))
        for predicate in SUBJECT_ID_PREDICATES
        for agent, sid in graph.subject_objects(predicate)
    ]
    wanted = normalise_subject_id(subject_id)
    matches = {}
    for agent, sid in stored:
        if normalise_subject_id(sid) == wanted:
            matches.setdefault(agent, set()).add(sid)

    if len(matches) == 1:
        (agent, sids), = matches.items()
        print('Found subject ID %s as %s in NIDM file (agent: %s)'
              % (subject_id, ", ".join(sorted(sids)), agent))
        return agent
    if len(matches) > 1:
        found = ", ".join("%s (%s)" % (agent, ", ".join(sorted(sids)))
                          for agent, sids in sorted(matches.items(), key=lambda kv: str(kv[0])))
        matched_ids = sorted({sid for sids in matches.values() for sid in sids})
        if len(matched_ids) > 1:
            raise SubjectLookupError(
                "Subject ID %s matches %d agents in the input NIDM: %s; their stored subject IDs "
                "differ (%s), so they may be different participants and the stats cannot be "
                "attached to one of them; no output written"
                % (subject_id, len(matches), found, ", ".join(matched_ids))
            )
        owners = sorted((agent for agent in matches if _owns_anatomical_acquisition(graph, agent)),
                        key=str)
        if len(owners) != 1:
            owning = "none of them owns" if not owners else "%d of them own" % len(owners)
            which = " (%s)" % ", ".join(str(agent) for agent in owners) if owners else ""
            raise SubjectLookupError(
                "Subject ID %s matches %d agents in the input NIDM: %s; %s an anatomical MRI "
                "acquisition%s, so the stats cannot be attached to one of them; no output written"
                % (subject_id, len(matches), found, owning, which)
            )
        print('Subject ID %s matches %d agents in the input NIDM (%s); using %s, the only one '
              'that owns an anatomical MRI acquisition' % (subject_id, len(matches), found, owners[0]))
        return owners[0]
    input_ids = sorted({sid for agent, sid in stored if agent not in created_agents})
    if input_ids:
        raise SubjectLookupError(
            "Subject ID %s was not found in the input NIDM, which has subject IDs: %s; "
            "no output written" % (subject_id, ", ".join(input_ids))
        )
    if forceagent:
        return None
    raise SubjectLookupError(
        "Subject ID %s was not found in the input NIDM, which has no subject agents; "
        "no output written (--forcenidm adds a new agent for it)" % subject_id
    )


def select_acquisition(rows, acq_filenames, subjid):
    """Pick the anatomical AcquisitionObjects the stats were computed from.

    :param rows: query results with .acqObj and .filename (the input's nfo:filename)
    :param acq_filenames: file names (or paths) of the images the segmentation
        used, or None
    :param subjid: subject identifier, for messages
    :return: list of AcquisitionObjects to link; empty to leave the stats unlinked

    A subject can have several anatomical acquisitions (sessions, runs, acq-
    variants). With acq_filenames, each name must match, by file name, exactly
    one acquisition, and all of them are linked. Without it, a single candidate
    is linked. Anything else is left unlinked with a warning rather than
    linked to a guess.
    """
    if not acq_filenames:
        candidates = sorted({r.acqObj for r in rows}, key=str)
        if len(candidates) == 1:
            return candidates
        if not candidates:
            warnings.warn(f"No anatomical MRI AcquisitionObject found for subject {subjid}; "
                          f"the stats are not linked to an acquisition")
        else:
            warnings.warn(f"{len(candidates)} anatomical AcquisitionObjects found for subject "
                          f"{subjid}; the stats are not linked to an acquisition "
                          f"(-acq_filename names the ones used)")
        return []
    chosen = []
    for name in acq_filenames:
        want = os.path.basename(name)
        matches = sorted({r.acqObj for r in rows
                          if r.filename is not None and str(r.filename).split('/')[-1] == want},
                         key=str)
        if len(matches) != 1:
            warnings.warn(f"{len(matches)} anatomical AcquisitionObjects with file name {want} "
                          f"found for subject {subjid}; the stats are not linked to an acquisition")
            return []
        chosen.append(matches[0])
    return sorted(set(chosen), key=str)


def add_seg_data(nidmdoc,subjid,stats_entity_id, add_to_nidm=False, forceagent=False,
                 acq_filename=None):
    '''
    WIP: this function creates a NIDM file of brain volume data and if user supplied a NIDM-E file it will add brain volumes to the
    NIDM-E file for the matching subject ID
    :param nidmdoc:
    :param header:
    :param add_to_nidm:
    :param acq_filename: file names (or paths) of the anatomical images the
        stats came from, used to pick their AcquisitionObjects in the input
        NIDM (see select_acquisition)
    :return:
    '''


    # Identify the subject before the graph is touched: a lookup error leaves
    # nidmdoc as it was.
    if add_to_nidm:
        participant_agent = find_subject(nidmdoc, subjid, forceagent)

    #for each of the header items create a dictionary where namespaces are freesurfer
    niiri=Namespace("http://iri.nidash.org/")
    nidmdoc.bind("niiri",niiri)
    # add namespace for subject id
    ndar = Namespace(Constants.NDAR)
    nidmdoc.bind("ndar",ndar)
    dct = Namespace(Constants.DCT)
    nidmdoc.bind("dct",dct)
    sio = Namespace(Constants.SIO)
    nidmdoc.bind("sio",sio)


    software_activity = niiri[getUUID()]
    nidmdoc.add((software_activity,RDF.type,Constants.PROV['Activity']))
    nidmdoc.add((software_activity,Constants.DCT["description"],Literal("ANTS segmentation statistics")))
    fs = Namespace(Constants.ANTS)


    #create software agent and associate with software activity
    #search and see if a software agent exists for this software, if so use it, if not create it
    for software_uid in nidmdoc.subjects(predicate=Constants.NIDM_NEUROIMAGING_ANALYSIS_SOFTWARE,object=URIRef(Constants.ANTS) ):
        software_agent = software_uid
        break
    else:
        software_agent = niiri[getUUID()]
    nidmdoc.add((software_agent,RDF.type,Constants.PROV['Agent']))
    neuro_soft=Namespace(Constants.NIDM_NEUROIMAGING_ANALYSIS_SOFTWARE)
    nidmdoc.add((software_agent,Constants.NIDM_NEUROIMAGING_ANALYSIS_SOFTWARE,URIRef(Constants.ANTS)))
    nidmdoc.add((software_agent,RDF.type,Constants.PROV["SoftwareAgent"]))
    association_bnode = BNode()
    nidmdoc.add((software_activity,Constants.PROV['qualifiedAssociation'],association_bnode))
    nidmdoc.add((association_bnode,RDF.type,Constants.PROV['Association']))
    nidmdoc.add((association_bnode,Constants.PROV['hadRole'],Constants.NIDM_NEUROIMAGING_ANALYSIS_SOFTWARE))
    nidmdoc.add((association_bnode,Constants.PROV['agent'],software_agent))

    if not add_to_nidm:

        # create a new agent for subjid
        participant_agent = niiri[getUUID()]
        nidmdoc.add((participant_agent,RDF.type,Constants.PROV['Agent']))
        nidmdoc.add((participant_agent,URIRef(NIDM_SUBJECTID_URI),Literal(subjid, datatype=XSD.string)))


    else:
        if participant_agent is None:
            warnings.warn(
                f"The input NIDM has no subject agents; the stats are attached to a "
                f"new agent with subject ID {subjid} (--forcenidm)"
            )
            participant_agent = niiri[getUUID()]
            nidmdoc.add((participant_agent,RDF.type,Constants.PROV['Agent']))
            nidmdoc.add((participant_agent,URIRef(NIDM_SUBJECTID_URI),Literal(subjid, datatype=XSD.string)))


    if add_to_nidm:
        results = _anatomical_acquisitions(nidmdoc, participant_agent)
        for acquisition_obj in select_acquisition(results, acq_filename, subjid):
            nidmdoc.add((software_activity, Constants.PROV['used'], acquisition_obj))

    #create a blank node and qualified association with prov:Agent for participant
    association_bnode = BNode()
    nidmdoc.add((software_activity,Constants.PROV['qualifiedAssociation'],association_bnode))
    nidmdoc.add((association_bnode,RDF.type,Constants.PROV['Association']))
    nidmdoc.add((association_bnode,Constants.PROV['hadRole'],Constants.SIO["Subject"]))
    nidmdoc.add((association_bnode,Constants.PROV['agent'],participant_agent))

    # add association between ANTSStatsCollection and computation activity
    nidmdoc.add((URIRef(stats_entity_id.uri),Constants.PROV['wasGeneratedBy'],software_activity))

    # get project uuid from NIDM doc and make association with software_activity
    query = """
                        prefix nidm: <http://purl.org/nidash/nidm#>
                        PREFIX rdf:<http://www.w3.org/1999/02/22-rdf-syntax-ns#>

                        select distinct ?project
                        where {

                            ?project rdf:type nidm:Project .

                        }"""

    qres = nidmdoc.query(query)
    for row in qres:
        nidmdoc.add((software_activity, Constants.DCT["isPartOf"], row['project']))


